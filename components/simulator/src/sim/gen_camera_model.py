"""Add the training cameras (`cameras` in specs/robots/<robot>/robot.yaml) as gz camera sensors to
a model that gen_panda_sdf.py --mobile wrote (ported from the earlier pipeline):

  gen_camera_model.py <model dir> [<robot>]    rewrites <model dir>/model.sdf in place

Topic per camera: /<model>/<name>/image (+ camera_info). No video recorder plugin.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import spec
from revolve_common import specs


def sensor(c, model):
    pose = " ".join(f"{v:.9g}" for v in c["pose"])
    return ET.fromstring(f"""
      <sensor name="{c['name']}" type="camera">
        <pose>{pose}</pose>
        <always_on>true</always_on>
        <update_rate>{c['rate']}</update_rate>
        <topic>/{model}/{c['name']}/image</topic>
        <camera>
          <horizontal_fov>{c['hfov']}</horizontal_fov>
          <image><width>{c['width']}</width><height>{c['height']}</height><format>R8G8B8</format></image>
          <clip><near>{c['clip'][0]}</near><far>{c['clip'][1]}</far></clip>
        </camera>
      </sensor>""")


def main(model_dir, robot="mobile_panda"):
    path = Path(model_dir) / "model.sdf"
    tree = ET.parse(path)
    model = tree.getroot().find("model")
    if model.findall(".//sensor[@type='camera']"):
        raise SystemExit(f"{path} already has camera sensors: regenerate it first")
    cams = [c.model_dump() for c in specs.load(spec.SPECS / "robots" / robot / "robot.yaml").cameras]
    for c in cams:
        link = model.find(f"link[@name='{c['link']}']")
        if link is None:
            raise SystemExit(f"camera {c['name']}: no link {c['link']} in {path}")
        link.append(sensor(c, model.get("name")))
    tree.getroot().insert(0, ET.Comment(
        " Generated by components/simulator/src/sim/gen_panda_sdf.py (mobile), cameras added by "
        "gen_camera_model.py "))
    ET.indent(tree)
    tree.write(path, encoding="unicode", xml_declaration=True)
    text = path.read_text()
    n = len(ET.parse(path).getroot().findall(".//sensor[@type='camera']"))
    if n != len(cams) or "recorder" in text.lower():
        raise SystemExit(f"{path}: {n} cameras, expected {len(cams)} and no recorder")
    print(f"Wrote {path}: {', '.join(c['name'] + ' on ' + c['link'] for c in cams)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
