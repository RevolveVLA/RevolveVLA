"""scene.yaml -> world SDF: the scene's models (model:// includes at their poses) on the simulator's fixed defaults
(ground plane, sun, ambient light, 1 ms MuJoCo physics, the Sensors (ogre2), Contact, SceneBroadcaster and
UserCommands systems). Every model gets a PosePublisher (gz topic /model/<m>/pose: the model in the world, its links
in the model), articulated ones a JointStatePublisher (gz topic /world/<w>/model/<m>/joint_state).
No robot: the launch spawns it. The world is named after the scene.

  python3 -m revolve_sim.world <scene name | scene.yaml> [--repo DIR] [--out world.sdf]
"""
import argparse
import sys
from pathlib import Path
from xml.sax.saxutils import escape

from revolve_common import specs

HEADER = """<?xml version="1.0"?>
<!-- Generated by revolve_sim.world from {src}: do not edit. -->
<sdf version="1.11">
  <world name="{name}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics">
      <engine><filename>gz-physics-mujoco-plugin</filename></engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <gravity>0 0 -9.81</gravity>
    <scene>
      <ambient>0.45 0.45 0.45 1</ambient>
      <background>0.75 0.8 0.85 1</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>0.3 -0.4 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
        </collision>
      </link>
    </model>
"""
POSES = """      <plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher">
        <publish_model_pose>true</publish_model_pose>
        <publish_link_pose>true</publish_link_pose>
        <publish_nested_model_pose>false</publish_nested_model_pose>
        <use_pose_vector_msg>true</use_pose_vector_msg>
        <update_frequency>100</update_frequency>
      </plugin>
"""
JOINT_STATES = """      <plugin filename="gz-sim-joint-state-publisher-system" name="gz::sim::systems::JointStatePublisher">
        <update_rate>100</update_rate>
      </plugin>
"""


def scene_path(scene, repo):
    p = Path(scene)
    return p if p.suffix == ".yaml" else Path(repo) / "specs" / "scenes" / scene / "scene.yaml"


def make_world(scene, repo):
    """(world SDF text, scene, [absolute asset dirs] for GZ_SIM_RESOURCE_PATH, [articulated model entities])."""
    repo = Path(repo).resolve()
    path = scene_path(scene, repo)
    sc = specs.load(path)
    models, errors = specs.scene_models(sc, repo)
    if errors:
        raise specs.SpecError("\n".join([f"{path}:", *errors]))
    articulated = []
    out = [HEADER.format(src=escape(str(path.relative_to(repo) if path.is_relative_to(repo) else path)),
                         name=sc.name)]
    for ent, m in sc.models.items():
        nonzero = {j: q for j, q in m.joints.items() if q != 0.0}
        if nonzero:
            # gz-sim has no upstream way to start a joint away from its SDF zero (only position-holding controllers)
            raise specs.SpecError(f"{path}: models.{ent}.joints {nonzero}: nonzero initial joint positions are not "
                                  f"supported by the simulator yet")
        x, y, z, yaw = m.pose
        movable = any(t not in ("fixed", None) for t, _, _ in models[ent].joints.values())
        if movable:
            articulated.append(ent)
        out.append(f"    <include>\n      <name>{ent}</name>\n      <uri>model://{m.model}</uri>\n"
                   f"      <pose>{x} {y} {z} 0 0 {yaw}</pose>\n" + POSES + (JOINT_STATES if movable else "")
                   + "    </include>\n")
    out.append("  </world>\n</sdf>\n")
    return "".join(out), sc, [str(repo / d) for d in sc.assets], articulated


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("scene")
    ap.add_argument("--repo", default=".")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    try:
        text = make_world(a.scene, a.repo)[0]
    except specs.SpecError as e:
        sys.exit(str(e))
    if a.out:
        Path(a.out).write_text(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
